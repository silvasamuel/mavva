import uuid
from datetime import date, datetime

from sqlalchemy import Date, ForeignKey, String, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class Season(Base):
    """One calendar month (Brasília time). XP, level and the leaderboards
    restart when it ends; ends_on is the first day of the next season."""

    __tablename__ = "seasons"

    id: Mapped[int] = mapped_column(primary_key=True)
    number: Mapped[int] = mapped_column(unique=True)
    starts_on: Mapped[date] = mapped_column(Date)
    ends_on: Mapped[date] = mapped_column(Date)
    closed_at: Mapped[datetime | None] = mapped_column(default=None)


class SeasonResult(Base):
    """Where a player finished a season. Only players who earned XP in it."""

    __tablename__ = "season_results"
    __table_args__ = (UniqueConstraint("season_id", "user_id"),)

    # Generated by the database: rows arrive in one INSERT ... SELECT per season.
    id: Mapped[int] = mapped_column(primary_key=True)
    season_id: Mapped[int] = mapped_column(ForeignKey("seasons.id", ondelete="CASCADE"))
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    final_xp: Mapped[int]
    final_level: Mapped[int]
    rank_code: Mapped[str] = mapped_column(String(20))
    # Place on the global leaderboard; null for deactivated accounts, which it hides.
    position: Mapped[int | None] = mapped_column(default=None)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
